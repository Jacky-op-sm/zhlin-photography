import { test, expect } from '@playwright/test'

test('Photography opens the exhibition directly from desktop navigation', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('a[href^="/hobby"]')).toHaveCount(0)
  const photography = page.locator('.site-header').getByRole('link', { name: 'Photography', exact: true })
  await expect(photography).toHaveAttribute('href', '/photography')
  await expect(photography).not.toHaveAttribute('aria-haspopup')
  await photography.hover()
  await expect(page.locator('.site-nav-dropdown-shell[data-open="true"]')).toHaveCount(0)
  await photography.click()
  await expect(page).toHaveURL(/\/photography(?:#bangkok\/[^/]+)?$/)
  await expect(page.getByTestId('exhibition-position')).toContainText('Bangkok')
  await expect(page.getByTestId('exhibition-image')).toBeVisible()
  await expect(page.locator('.site-header')).toHaveCount(0)
  await page.getByRole('button', { name: 'Index', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Index', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: /Bangkok 16/ })).toBeVisible()
  await page.getByRole('dialog', { name: 'Index', exact: true }).getByRole('link', { name: 'Zhlin home', exact: true }).click()
  await expect(page).toHaveURL(/\/$/)
  await expect(page.locator('.site-header').getByRole('link', { name: 'Home', exact: true })).toHaveAttribute('href', '/')
  const brand = page.getByRole('link', { name: '打开摄影展览', exact: true })
  await expect(brand).toHaveAttribute('href', '/photography')
  await brand.click()
  await expect(page).toHaveURL(/\/photography(?:#bangkok\/[^/]+)?$/)
  await expect(page.getByTestId('exhibition-position')).toContainText('Bangkok')
  await expect(page.getByTestId('exhibition-image')).toBeVisible()
})
